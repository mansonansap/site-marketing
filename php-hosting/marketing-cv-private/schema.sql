CREATE TABLE IF NOT EXISTS cv_state (
 id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
 draft LONGTEXT NOT NULL, published LONGTEXT NOT NULL, preview LONGTEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS cv_admin (
 id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
 username VARCHAR(80) NOT NULL, password_hash VARCHAR(255) NOT NULL, version CHAR(64) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS cv_messages (
 id CHAR(32) NOT NULL PRIMARY KEY, created_at VARCHAR(30) NOT NULL,
 name VARCHAR(100) NOT NULL, contact VARCHAR(200) NOT NULL, message TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS cv_backups (
 revision INT UNSIGNED NOT NULL PRIMARY KEY, content LONGTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS cv_limits (
 bucket CHAR(64) NOT NULL, slot BIGINT UNSIGNED NOT NULL, hits INT UNSIGNED NOT NULL,
 PRIMARY KEY(bucket, slot)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
